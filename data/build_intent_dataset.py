SPLIT = {"train": 0.8, "dev": 0.1, "test": 0.1}


def expand(label, templates, per_template=15):
    """每个模板生成多条样本；模板是切分单元，防止同模板句子跨集合泄漏。"""
    rows = []  # (template_id, text, label)
    for tid, tpl in enumerate(templates):
        seen = set()
        for _ in range(per_template):
            text = tpl.format(c=random.choice(CRIMES), a=random.choice(LAW_ARTICLES),
                              m=random.choice(AMOUNTS), p=random.choice(PLACES),
                              t=random.choice(TIMES))
            if text not in seen:
                seen.add(text)
                rows.append((tid, text, label))
    return rows


def main():
    all_rows = []
    for label, templates in TEMPLATES.items():
        all_rows.extend(expand(label, templates))

    # 模板级 + 类别分层切分：同一模板的句子只进一个集合（防泄漏），
    # 且每个类在 dev/test 至少保留 1 个模板（保证每类都有评估样本）
    groups = {}
    for tid, text, label in all_rows:
        groups.setdefault((label, tid), []).append(text)

    by_label = {}
    for (label, tid), texts in groups.items():
        by_label.setdefault(label, []).append((tid, texts))

    buckets = {"train": [], "dev": [], "test": []}
    for label, tpl_groups in sorted(by_label.items()):
        random.shuffle(tpl_groups)
        k = len(tpl_groups)
        n_test = max(1, round(k * 0.1)) if k >= 5 else (1 if k >= 3 else 0)
        n_dev = max(1, round(k * 0.1)) if k >= 5 else (1 if k >= 3 else 0)
        for i, (tid, texts) in enumerate(tpl_groups):
            bucket = "test" if i < n_test else ("dev" if i < n_test + n_dev else "train")
            for t in texts:
                buckets[bucket].append((t, label))

    for name, rows in buckets.items():
        random.shuffle(rows)
        path = OUT / f"intent_{name}.csv"
        with open(path, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["text", "label"])
            w.writerows(rows)
        print(f"{path.name}: {len(rows)} 条")

    labels = sorted(TEMPLATES.keys())
    (OUT / "labels.txt").write_text("\n".join(labels), encoding="utf-8")
    print(f"共 {len(labels)} 类意图: {labels}")


if __name__ == "__main__":
    main()
